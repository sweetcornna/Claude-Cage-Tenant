#!/usr/bin/env node
// Native brand assets for Super Cage, generated from the hand-drawn SVGs in
// mobile/assets/brand (ink = currentColor, accent = clay #D97757).
//
//   node mobile/scripts/brand-assets.mjs           write the iOS imagesets and Android vector drawables
//   node mobile/scripts/brand-assets.mjs --check   exit 1 when the checked-in outputs are stale
//   PLAYWRIGHT=<playwright module dir> CHROME=<chrome binary> \
//     node mobile/scripts/brand-assets.mjs --icons render the 1024 px iOS AppIcon (macOS, uses sips)
//
// iOS gets one SVG per appearance (ink #1F1E1D / #F3EFE5) with vector data preserved.
// Android vectors read the ink from the theme attribute ?attr/cageInk; clay stays fixed.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, mkdtempSync, rmSync } from "node:fs";
import { dirname, join, basename } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { execFileSync } from "node:child_process";
import { tmpdir } from "node:os";

const mobile = fileURLToPath(new URL("../", import.meta.url));
const brand = join(mobile, "assets/brand");
const catalog = join(mobile, "ios/CageMobile/Assets.xcassets");
const drawables = join(mobile, "android/res/drawable");
export const INK = { light: "#1F1E1D", dark: "#F3EFE5" };
export const CLAY = "#D97757";
export const ICON_BACKGROUND = "#F5F0E6";
const generated = "Generated by mobile/scripts/brand-assets.mjs from mobile/assets/brand. Do not edit.";

const attributes = (text) => Object.fromEntries([...text.matchAll(/([\w:-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
// "currentColor" is the ink; the doodles name the accent as var(--clay, #D97757).
function paint(value) {
  if (value === undefined || value === "none") return null;
  if (value === "currentColor") return "ink";
  const color = /^var\(--clay,\s*(#[0-9a-fA-F]{6})\)$/.exec(value)?.[1] ?? value;
  if (!/^#[0-9a-fA-F]{6}$/.test(color)) throw new Error("unsupported paint " + value);
  return color.toUpperCase();
}
const number = (value, fallback) => (value === undefined ? fallback : Number(value));

export function parseSvg(text) {
  const root = /<svg\b([^>]*)>/.exec(text);
  if (!root) throw new Error("missing <svg>");
  const top = attributes(root[1]);
  const box = top.viewBox?.split(/[\s,]+/).map(Number);
  if (!box || box.length !== 4 || box.some(Number.isNaN) || box[0] !== 0 || box[1] !== 0) throw new Error("unsupported viewBox");
  const paths = [...text.matchAll(/<path\b([^>]*?)\/?>/g)].map((m) => {
    const own = attributes(m[1]);
    const get = (name) => own[name] ?? top[name];
    // Element opacity applies to stroke and fill alike; no path here overlaps itself.
    const opacity = number(own.opacity, 1);
    return {
      d: own.d,
      fill: paint(get("fill") ?? "#000000"),
      stroke: paint(get("stroke")),
      strokeWidth: number(get("stroke-width"), 1),
      cap: get("stroke-linecap") ?? "butt",
      join: get("stroke-linejoin") ?? "miter",
      fillAlpha: opacity * number(own["fill-opacity"], 1),
      strokeAlpha: opacity * number(own["stroke-opacity"], 1),
    };
  });
  if (!paths.length || paths.some((p) => !p.d)) throw new Error("missing path data");
  return { width: box[2], height: box[3], paths };
}

const usesInk = (svg) => svg.paths.some((p) => p.fill === "ink" || p.stroke === "ink");
const alpha = (value) => String(Math.round(value * 1000) / 1000);

export function iosSvg(svg, ink) {
  const color = (value) => (value === "ink" ? ink : value);
  const lines = svg.paths.map((p) => {
    const parts = [`d="${p.d}"`, `fill="${p.fill ? color(p.fill) : "none"}"`];
    if (p.fill && p.fillAlpha !== 1) parts.push(`fill-opacity="${alpha(p.fillAlpha)}"`);
    if (p.stroke) {
      parts.push(`stroke="${color(p.stroke)}"`, `stroke-width="${p.strokeWidth}"`,
        `stroke-linecap="${p.cap}"`, `stroke-linejoin="${p.join}"`);
      if (p.strokeAlpha !== 1) parts.push(`stroke-opacity="${alpha(p.strokeAlpha)}"`);
    }
    return `  <path ${parts.join(" ")}/>`;
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${svg.width}" height="${svg.height}" viewBox="0 0 ${svg.width} ${svg.height}">\n${lines.join("\n")}\n</svg>\n`;
}

const argb = (hex) => "#FF" + hex.slice(1);
// options.ink: Android color for ink paths (default: the theme attribute).
// options.all: paint every path in this color (adaptive icon monochrome layer).
// options.frame: [size, scale, dx, dy] wraps the art in a group on a square viewport.
export function androidVector(svg, options = {}) {
  const ink = options.ink ?? "?attr/cageInk";
  const color = (value) => (options.all ? options.all : value === "ink" ? ink : argb(value));
  const indent = options.frame ? "        " : "    ";
  const paths = svg.paths.map((p) => {
    const parts = [`android:pathData="${p.d}"`];
    if (p.fill) {
      parts.push(`android:fillColor="${color(p.fill)}"`);
      if (p.fillAlpha !== 1) parts.push(`android:fillAlpha="${alpha(p.fillAlpha)}"`);
    }
    if (p.stroke) {
      parts.push(`android:strokeColor="${color(p.stroke)}"`, `android:strokeWidth="${p.strokeWidth}"`,
        `android:strokeLineCap="${p.cap}"`, `android:strokeLineJoin="${p.join}"`);
      if (p.strokeAlpha !== 1) parts.push(`android:strokeAlpha="${alpha(p.strokeAlpha)}"`);
    }
    return `${indent}<path ${parts.join(`\n${indent}    `)} />`;
  });
  let body = paths.join("\n");
  let size = [svg.width, svg.height, svg.width, svg.height];
  if (options.frame) {
    const [side, scale, dx, dy] = options.frame;
    size = [side, side, side, side];
    body = `    <group android:scaleX="${scale}" android:scaleY="${scale}" android:translateX="${dx}" android:translateY="${dy}">\n${body}\n    </group>`;
  }
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${generated} -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n` +
    `    android:width="${size[0]}dp" android:height="${size[1]}dp" android:viewportWidth="${size[2]}" android:viewportHeight="${size[3]}">\n${body}\n</vector>\n`;
}

const json = (value) => JSON.stringify(value, null, 2) + "\n";
const info = { author: "xcode", version: 1 };
function imageset(name, svg) {
  const files = new Map();
  const images = [{ filename: name + ".svg", idiom: "universal" }];
  files.set(name + ".svg", iosSvg(svg, INK.light));
  if (usesInk(svg)) {
    images.push({ appearances: [{ appearance: "luminosity", value: "dark" }], filename: name + "-dark.svg", idiom: "universal" });
    files.set(name + "-dark.svg", iosSvg(svg, INK.dark));
  }
  files.set("Contents.json", json({ images, info, properties: { "preserves-vector-representation": true } }));
  return files;
}

// The app icon shows the logo at about 62% of the visible icon on ivory.
// Adaptive icons draw 108 dp layers and show at least the inner 72 dp.
export function iconFrame(svg, side = 108, visible = 72, share = 0.62) {
  const scale = Math.round(((visible * share) / svg.width) * 1000) / 1000;
  const offset = Math.round(((side - svg.width * scale) / 2) * 1000) / 1000;
  return [side, scale, offset, offset];
}

export function outputs() {
  const files = new Map();
  const logo = parseSvg(readFileSync(join(brand, "logo.svg"), "utf8"));
  const sets = [["Logo", logo]];
  const vectors = [["cage_logo", logo]];
  for (const file of readdirSync(join(brand, "doodles")).filter((f) => f.endsWith(".svg")).sort()) {
    const name = basename(file, ".svg");
    const svg = parseSvg(readFileSync(join(brand, "doodles", file), "utf8"));
    sets.push(["Doodle" + name[0].toUpperCase() + name.slice(1), svg]);
    vectors.push(["cage_doodle_" + name, svg]);
  }
  files.set(join(catalog, "Contents.json"), json({ info }));
  for (const [name, svg] of sets)
    for (const [file, text] of imageset(name, svg)) files.set(join(catalog, name + ".imageset", file), text);
  files.set(join(catalog, "AppIcon.appiconset/Contents.json"), json({
    images: [{ filename: "AppIcon.png", idiom: "universal", platform: "ios", size: "1024x1024" }], info,
  }));
  for (const [name, svg] of vectors) files.set(join(drawables, name + ".xml"), androidVector(svg));
  const frame = iconFrame(logo);
  files.set(join(drawables, "cage_icon_foreground.xml"), androidVector(logo, { ink: argb(INK.light), frame }));
  files.set(join(drawables, "cage_icon_monochrome.xml"), androidVector(logo, { all: "#FFFFFFFF", frame }));
  return files;
}

function renderIcon() {
  const { PLAYWRIGHT, CHROME } = process.env;
  if (!PLAYWRIGHT || !CHROME) throw new Error("Set PLAYWRIGHT to the playwright module directory and CHROME to a Chrome binary.");
  return import(pathToFileURL(join(PLAYWRIGHT, "index.mjs"))).then(async ({ chromium }) => {
    const art = iosSvg(parseSvg(readFileSync(join(brand, "logo.svg"), "utf8")), INK.light);
    const page = `<!doctype html><style>html,body{margin:0;background:${ICON_BACKGROUND}}div{width:1024px;height:1024px;display:grid;place-items:center}svg{width:635px;height:635px}</style><div>${art}</div>`;
    const browser = await chromium.launch({ executablePath: CHROME });
    const work = mkdtempSync(join(tmpdir(), "cage-icon-"));
    try {
      const tab = await browser.newPage({ viewport: { width: 1024, height: 1024 }, deviceScaleFactor: 1 });
      await tab.setContent(page);
      // App Store icons must not carry an alpha channel; JPEG round-trip drops it.
      await tab.screenshot({ path: join(work, "icon.jpg"), type: "jpeg", quality: 100 });
      const out = join(catalog, "AppIcon.appiconset/AppIcon.png");
      mkdirSync(dirname(out), { recursive: true });
      execFileSync("sips", ["-s", "format", "png", join(work, "icon.jpg"), "--out", out], { stdio: "ignore" });
      console.log(out);
    } finally {
      await browser.close();
      rmSync(work, { recursive: true, force: true });
    }
  });
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const mode = process.argv[2];
  if (mode === "--icons") await renderIcon();
  else {
    const stale = [];
    for (const [path, text] of outputs()) {
      if (existsSync(path) && readFileSync(path, "utf8") === text) continue;
      if (mode === "--check") { stale.push(path); continue; }
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, text);
    }
    if (stale.length) {
      console.error("Stale brand assets; run node mobile/scripts/brand-assets.mjs:\n" + stale.join("\n"));
      process.exit(1);
    }
  }
}
